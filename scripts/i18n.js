/* ── Appliquer les traductions ── */
function applyTranslations(lang) {
  const t = TRANSLATIONS[lang];
  if (!t) return;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      // innerHTML pour permettre les balises <em>, <br>
      el.innerHTML = t[key];
    }
  });

  // Attributs (placeholder, aria-label, title, alt)
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key]) el.placeholder = t[key];
  });

  // Mettre à jour lang sur <html>
  document.documentElement.lang = lang;
}

/* ── Initialisation ── */
function initI18n() {
  const saved = localStorage.getItem('tomasteed_lang') || 'fr';
  window.__lang = saved;
  applyTranslations(saved);

  const toggle = document.getElementById('langToggle');
  if (!toggle) return;

  // Afficher la langue opposée dans le bouton
  toggle.textContent = saved === 'fr' ? 'FR / EN' : 'EN / FR';

  toggle.addEventListener('click', () => {
    const next = window.__lang === 'fr' ? 'en' : 'fr';
    window.__lang = next;
    localStorage.setItem('tomasteed_lang', next);
    toggle.textContent = next === 'fr' ? 'FR / EN' : 'EN / FR';
    applyTranslations(next);
  });
}

// Lancer dès que le DOM est prêt
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
